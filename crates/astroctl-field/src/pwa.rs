#[cfg(pwa_embedded)]
fn shell(path: &str) -> Response {
    // `include_dir` resolves against an in-memory index built at compile time, so a `..` in the
    // request addresses nothing rather than escaping to the filesystem — there is no filesystem
    // in this lookup to escape to.
    //
    // The path is not percent-decoded. Every name Vite emits is ASCII and hash-derived, so there
    // is nothing to decode; if that ever stops being true the symptom is an asset 404 that falls
    // through to the shell, which is visible immediately rather than subtly wrong.
    let relative = path.trim_start_matches('/');
    match DIST.get_file(relative) {
        Some(file) => asset(relative, file.contents()),
        // The SPA fallback: any path that is not a file is a client-side route.
        None => index(),
    }
}

#[cfg(pwa_embedded)]
fn index() -> Response {
    match DIST.get_file("index.html") {
        Some(file) => asset("index.html", file.contents()),
        // Unreachable: build.rs only sets `pwa_embedded` when `frontend/dist/index.html` exists.
        None => ApiFailure(ApiError::new(
            ErrorCode::Internal,
            "the embedded UI bundle has no index.html",
        ))
        .into_response(),
    }
}

#[cfg(pwa_embedded)]
fn asset(path: &str, bytes: &'static [u8]) -> Response {
    (
        [
            (header::CONTENT_TYPE, content_type(path)),
            (header::CACHE_CONTROL, cache_control(path)),
        ],
        // `from_static` rather than a copy: the bytes are in the binary's read-only data and the
        // body borrows them, so serving a 200 KB bundle to ten clients allocates nothing.
        Body::from(axum::body::Bytes::from_static(bytes)),
    )
        .into_response()
}

/// Media type by extension.
///
/// A table rather than a `mime_guess` dependency: the set of extensions a Vite build emits is
/// small, known, and changes when someone adds an asset kind on purpose. `application/octet-stream`
/// for anything else is the safe default — a browser will not execute what it cannot identify.
#[cfg(pwa_embedded)]
fn content_type(path: &str) -> &'static str {
    match path.rsplit_once('.').map(|(_, extension)| extension) {
        Some("html") => "text/html; charset=utf-8",
        Some("js") => "text/javascript; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("json") => "application/json",
        // Chrome will not treat the file as a manifest under any other type, and the install
        // prompt (USB-09) simply never appears.
        Some("webmanifest") => "application/manifest+json",
        Some("svg") => "image/svg+xml",
        Some("png") => "image/png",
        Some("ico") => "image/x-icon",
        Some("woff2") => "font/woff2",
        Some("txt") => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}

/// How long a browser may keep a file without asking.
///
/// Everything under `/assets/` carries a content hash in its name, so it can be cached forever:
/// a change produces a different name. Everything else must be revalidated, and `sw.js` is the
/// reason this matters rather than a nicety — a service worker cached at the HTTP layer is one
/// that cannot be replaced until the cache expires, which makes a bad worker unfixable remotely
/// on a machine at the end of a VPN.
#[cfg(pwa_embedded)]
fn cache_control(path: &str) -> &'static str {
    if path.starts_with("assets/") {
        "public, max-age=31536000, immutable"
    } else {
        "no-cache"
    }
}

