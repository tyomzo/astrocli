//! Serving the embedded operator UI — ARC-02, USB-09/10, SDD §5.9. This is the M0-T06 half of the
//! static-asset seam described in [`crate::api`].
//!
//! # Two subtrees, one origin, one auth policy each
//!
//! [`router`] is merged *outside* the bearer-auth layer, and it has to be: a browser cannot put an
//! `Authorization` header on the navigation request that loads an app shell. The shell is
//! therefore public and the API is not, which is safe because the shell is a static bundle that
//! knows nothing — every fact it displays comes from a request the operator's token has to carry.
//!
//! # What happens to an API path that matches no route
//!
//! Merging an unauthenticated fallback under `/` is where this could quietly undo a property
//! M0-T05 established: auth sits outside routing so that "the token is wrong" and "that path does
//! not exist" are indistinguishable, and an unauthenticated caller cannot map the API by probing.
//! A fallback that returned the app shell for `/api/mount/position` would give that away — 200
//! HTML for a path that does not exist, 401 for one that does.
//!
//! So this fallback does not serve the shell for API-shaped paths. It re-runs the same
//! [`AuthPolicy::authorize`] the layer runs and renders the same 401 through the same function
//! ([`crate::auth::unauthorized`]) — identical by construction rather than by two copies staying
//! in step — and only answers 404 to a caller that has already proved it may know the difference.
//!
//! # Absent bundle
//!
//! `frontend/dist` is generated by npm and git-ignored, so it is missing from every fresh clone.
//! `build.rs` sets `cfg(pwa_embedded)` when it exists; without it this module compiles a
//! placeholder page instead, and `cargo build -p astroctl-field` works with no Node toolchain
//! anywhere on the machine.

