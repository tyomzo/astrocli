/// What `/` serves when the binary was built without `frontend/dist`.
///
/// 200, not 503. The node is not degraded: every API route works, the watchdogs run, and a
/// container health check pointed at this binary is telling the truth when it says the service is
/// up. The missing thing is a browser bundle, and the only party who needs to know is the person
/// reading this page.
///
/// It carries no colours — `color-scheme: dark` is enough to keep it from flashing white at
/// someone at 2 a.m. — because a literal palette here would be a second, unmaintained copy of the
/// token layer that nobody would think to update.
#[cfg(not(pwa_embedded))]
fn shell(_path: &str) -> Response {
    const PAGE: &str = concat!(
        "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">",
        "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">",
        "<title>AstroCtl — operator UI not built</title>",
        "<style>:root{color-scheme:dark}body{font:1rem/1.6 system-ui,sans-serif;",
        "margin:0;min-height:100dvh;display:grid;place-items:center;padding:2rem}",
        "main{max-width:36rem}code,pre{font-family:ui-monospace,monospace}",
        "pre{padding:1rem;border:1px solid;border-radius:.5rem;overflow-x:auto}</style>",
        "</head><body><main>",
        "<h1>The operator UI is not in this binary</h1>",
        "<p>This <code>astroctl-field</code> was built without <code>frontend/dist</code>, so ",
        "there is no PWA to serve. The API is unaffected — <code>/api/system/health</code> and ",
        "<code>/api/system/info</code> answer normally.</p>",
        "<pre>scripts/build-frontend.sh\ncargo build -p astroctl-field</pre>",
        "<p>The bundle is git-ignored and generated by npm, so a fresh clone always starts here. ",
        "Building it is not part of <code>cargo build</code> on purpose: nobody working on the ",
        "Rust side should need a Node toolchain to run the tests.</p>",
        "</main></body></html>"
    );

    (
        [
            (header::CONTENT_TYPE, "text/html; charset=utf-8"),
            (header::CACHE_CONTROL, "no-store"),
        ],
        Body::from(PAGE),
    )
        .into_response()
}

