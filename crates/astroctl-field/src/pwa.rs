    /// including the API misses — there is no credential to be wrong.
    #[tokio::test]
    async fn an_open_loopback_node_serves_the_shell_and_a_plain_404() {
        let node = TestNode::open_loopback();
        assert_eq!(get(&node, "/", None).await.status, StatusCode::OK);

        let answer = get(&node, "/api/nope", None).await;
        assert_eq!(answer.status, StatusCode::NOT_FOUND);
        assert_eq!(answer.json()["code"], "NOT_FOUND");
    }

    /// The 401 the fallback renders must be the one the middleware renders, challenge header and
    /// all — the module docs claim they are identical by construction, so this checks it.
    #[tokio::test]
    async fn the_fallbacks_401_is_the_middlewares_401() {
        let node = TestNode::authenticated("s3cret");
        let (router, declarations) = api::router();
        let state = state_with(&node, declarations);
        let app = crate::assemble(router, state);

        let mut responses = Vec::new();
        for path in ["/api/system/health", "/api/undeclared"] {
            let response = app
                .clone()
                .oneshot(
                    Request::builder()
                        .uri(path)
                        .header(header::AUTHORIZATION, HeaderValue::from_static("Bearer no"))
                        .body(Body::empty())
                        .expect("request builds"),
                )
                .await
                .expect("router responds");
            assert_eq!(response.status(), StatusCode::UNAUTHORIZED, "for {path}");
            responses.push((
                response
                    .headers()
                    .get(header::WWW_AUTHENTICATE)
                    .cloned()
                    .expect("RFC 6750 §3 challenge"),
                to_bytes(response.into_body(), 1 << 20)
                    .await
                    .expect("body reads"),
            ));
        }
        assert_eq!(responses[0], responses[1]);
    }
