    struct Answer {
        status: StatusCode,
        content_type: String,
        cache_control: String,
        body: Vec<u8>,
    }

    impl Answer {
        fn text(&self) -> String {
            String::from_utf8_lossy(&self.body).into_owned()
        }

        fn json(&self) -> Value {
            serde_json::from_slice(&self.body).unwrap_or(Value::Null)
        }
    }

    /// Drive the *assembled* application — the API with its auth layer plus this router merged
    /// onto it — because everything interesting here is a property of the merge, not of either
    /// half. `crate::assemble` is the same function `main` calls.
    async fn call(node: &TestNode, method: Method, path: &str, token: Option<&str>) -> Answer {
        let (router, declarations) = api::router();
        let state = state_with(node, declarations);
        let app = crate::assemble(router, state);

        let mut request = Request::builder().method(method).uri(path);
        if let Some(token) = token {
            request = request.header(header::AUTHORIZATION, format!("Bearer {token}"));
        }
        let response = app
            .oneshot(request.body(Body::empty()).expect("request builds"))
            .await
            .expect("router responds");

        let status = response.status();
        let headers = response.headers().clone();
        let read = |name: header::HeaderName| {
            headers
                .get(name)
                .and_then(|v| v.to_str().ok())
                .unwrap_or_default()
                .to_owned()
        };
        Answer {
            status,
            content_type: read(header::CONTENT_TYPE),
            cache_control: read(header::CACHE_CONTROL),
            body: to_bytes(response.into_body(), 8 << 20)
                .await
                .expect("body reads")
                .to_vec(),
        }
    }

    async fn get(node: &TestNode, path: &str, token: Option<&str>) -> Answer {
        call(node, Method::GET, path, token).await
    }

    // --- the merge must not weaken M0-T05's auth posture -------------------------------

